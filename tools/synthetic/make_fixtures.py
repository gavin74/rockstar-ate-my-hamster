#!/usr/bin/env python3
"""Generate SYNTHETIC test fixtures that match the formats the pipeline reads.

Usage: make_fixtures.py <out_dir>

Writes:
  side_a.tzx      header "CODE1" + one data block of filler bytes. It has no game code.
  side_b.tzx      50 headerless data blocks of 250 bytes (10 stats + 240 portrait
                  bytes), the shape tools/setup_assets.sh counts as rock star records.
  gamedata.json   a gamedata.json with the schema of web/src/data.ts and random-looking
                  but fake table values. It is NOT the output of make_assets.py.

Nothing here comes from the original game. The output is deterministic (fixed seed)
so tests can compare it. Real data must come from the user's own tapes.
"""
import json
import os
import random
import struct
import sys

NOTICE = "SYNTHETIC: generated by tools/synthetic/make_fixtures.py. Not game data."


def checksum(block):
    c = 0
    for b in block:
        c ^= b
    return c


def std_block(flag, payload, pause=1000):
    body = bytes([flag]) + payload
    body += bytes([checksum(body)])
    return b"\x10" + struct.pack("<HH", pause, len(body)) + body


def header_block(name, typ=3, length=0, p1=0, p2=0):
    payload = bytes([typ]) + name.encode("latin-1").ljust(10, b" ")[:10]
    payload += struct.pack("<HHH", length, p1, p2)
    return std_block(0x00, payload)


def tzx(blocks):
    return b"ZXTape!\x1a" + bytes([1, 20]) + b"".join(blocks)


def side_a(rng):
    filler = bytes(rng.randrange(256) for _ in range(512))
    return tzx([header_block("CODE1", typ=3, length=len(filler), p1=32768), std_block(0xFF, filler)])


def side_b(rng):
    blocks = []
    for _ in range(50):
        rec = bytes(rng.randrange(256) for _ in range(250))
        blocks.append(std_block(0xFF, rec))
    return tzx(blocks)


def gamedata(rng):
    rng_table = [i % 16 for i in range(64)]
    rng.shuffle(rng_table)
    if 0 not in rng_table:
        rng_table[0] = 0
    rivals = [
        {
            "single": [rng.randrange(256) for _ in range(5)],
            "album": [rng.randrange(256) for _ in range(5)],
            "songChoices": [rng.randrange(58) for _ in range(3)],
            "albumTitle": rng.randrange(58),
        }
        for _ in range(30)
    ]
    text = lambda s: [{"t": "text", "v": s}]
    return {
        "_notice": NOTICE,
        "rngTable": rng_table,
        "rivals": rivals,
        "respawnScores": [25, 45, 33, 21, 19, 36],
        "respawnStart": 3,
        "nameStrings": [text(f"SYNTH TITLE {i:02d}") for i in range(58)],
        "bandNames": [text(f"SYNTH BAND {i}") for i in range(8)],
        "videoRankTable": list(range(10)),
        "fameRankTable": list(range(10)),
        "royaltyPercent": [255, 10, 20, 30, 40, 50],
        "studioDays": [5, 4, 3, 2],
    }


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    os.makedirs(out, exist_ok=True)
    rng = random.Random(20261024)
    files = {
        "side_a.tzx": side_a(rng),
        "side_b.tzx": side_b(rng),
    }
    for name, data in files.items():
        with open(os.path.join(out, name), "wb") as f:
            f.write(data)
    with open(os.path.join(out, "gamedata.json"), "w") as f:
        json.dump(gamedata(rng), f, indent=1)
        f.write("\n")
    print("wrote", ", ".join(sorted(os.listdir(out))), "to", out)


if __name__ == "__main__":
    main()
